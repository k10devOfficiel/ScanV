<?php

declare(strict_types=1);

namespace App\Services;

use App\Core\Database;
use App\Core\Env;
use App\Helpers\Security;
use App\Models\BusinessCard;
use App\Models\User;
use App\Repositories\BusinessCardRepository;
use App\Repositories\UserRepository;
use PDO;

/**
 * Authentication Service (F-02, F-03, F-04).
 * Handles registration, login, logout, session security, and rate limiting.
 */
class AuthService
{
    private PDO $pdo;
    private UserRepository $userRepo;
    private BusinessCardRepository $cardRepo;

    public const MAX_LOGIN_ATTEMPTS = 5;
    public const LOCKOUT_MINUTES = 15;

    public function __construct(
        ?PDO $pdo = null,
        ?UserRepository $userRepo = null,
        ?BusinessCardRepository $cardRepo = null
    ) {
        $this->pdo = $pdo ?? Database::getConnection();
        $this->userRepo = $userRepo ?? new UserRepository($this->pdo);
        $this->cardRepo = $cardRepo ?? new BusinessCardRepository($this->pdo);
    }

    /**
     * Register a new user and automatically generate default business card (F-02).
     *
     * @param array<string, mixed> $input
     * @return array{success: bool, errors: array<string, string>, user: ?User, card: ?BusinessCard}
     */
    public function register(array $input): array
    {
        $errors = [];

        $firstName = trim((string) ($input['first_name'] ?? ''));
        $lastName = trim((string) ($input['last_name'] ?? ''));
        $email = trim(strtolower((string) ($input['login_email'] ?? '')));
        $password = (string) ($input['password'] ?? '');
        $passwordConfirm = (string) ($input['password_confirmation'] ?? '');
        $termsAccepted = !empty($input['terms']);

        // Validation
        if ($firstName === '') {
            $errors['first_name'] = 'Le prénom est obligatoire.';
        } elseif (mb_strlen($firstName) > 100) {
            $errors['first_name'] = 'Le prénom ne doit pas dépasser 100 caractères.';
        }

        if ($lastName === '') {
            $errors['last_name'] = 'Le nom est obligatoire.';
        } elseif (mb_strlen($lastName) > 100) {
            $errors['last_name'] = 'Le nom ne doit pas dépasser 100 caractères.';
        }

        if ($email === '') {
            $errors['login_email'] = 'L\'adresse e-mail est obligatoire.';
        } elseif (!filter_var($email, FILTER_VALIDATE_EMAIL)) {
            $errors['login_email'] = 'L\'adresse e-mail saisie n\'est pas valide.';
        } elseif (mb_strlen($email) > 191) {
            $errors['login_email'] = 'L\'adresse e-mail ne doit pas dépasser 191 caractères.';
        } else {
            // Check email uniqueness
            $existing = $this->userRepo->findByEmail($email);
            if ($existing !== null) {
                $errors['login_email'] = 'Cette adresse e-mail est déjà associée à un compte existant.';
            }
        }

        if ($password === '') {
            $errors['password'] = 'Le mot de passe est obligatoire.';
        } elseif (mb_strlen($password) < 10) {
            $errors['password'] = 'Le mot de passe doit comporter au moins 10 caractères.';
        }

        if ($password !== $passwordConfirm) {
            $errors['password_confirmation'] = 'La confirmation ne correspond pas au mot de passe saisi.';
        }

        if (!$termsAccepted) {
            $errors['terms'] = 'Vous devez accepter les conditions d\'utilisation et la politique de confidentialité.';
        }

        if (!empty($errors)) {
            return [
                'success' => false,
                'errors' => $errors,
                'user' => null,
                'card' => null,
            ];
        }

        // Database transaction: create user + create initial business card + visibility
        $this->pdo->beginTransaction();
        try {
            $user = $this->userRepo->create([
                'first_name' => $firstName,
                'last_name' => $lastName,
                'login_email' => $email,
                'password' => $password,
                'status' => 'active',
            ]);

            // Rule 5: public_id is 32 hex generated by random_bytes(16)
            $publicId = Security::generatePublicId();

            $card = $this->cardRepo->create([
                'user_id' => $user->id,
                'public_id' => $publicId,
                'display_first_name' => $firstName,
                'display_last_name' => $lastName,
                'job_title' => null,
                'department' => null,
                'company_name' => null,
                'company_website' => null,
                'company_address' => null,
                'professional_phone' => null,
                'professional_email' => null,
                'photo_path' => null,
                'logo_path' => null,
                'theme_key' => 'default',
                'is_active' => 1,
                // Card visibility defaults
                'show_photo' => 0,
                'show_job_title' => 1,
                'show_department' => 0,
                'show_company' => 1,
                'show_company_address' => 0,
                'show_phone' => 0,
                'show_email' => 0,
                'show_website' => 0,
                'show_social_links' => 0,
            ]);

            $this->pdo->commit();

            // Automatically authenticate user after registration
            $this->startUserSession($user);

            return [
                'success' => true,
                'errors' => [],
                'user' => $user,
                'card' => $card,
            ];
        } catch (\Throwable $e) {
            if ($this->pdo->inTransaction()) {
                $this->pdo->rollBack();
            }
            throw $e;
        }
    }

    /**
     * Authenticate user with credentials and rate limiting (F-03).
     *
     * @return array{success: bool, error: ?string, user: ?User}
     */
    public function login(string $email, string $password, string $ip): array
    {
        $email = trim(strtolower($email));

        // 1. Check rate limit
        if ($this->isRateLimited($ip, $email)) {
            return [
                'success' => false,
                'error' => 'Trop de tentatives échouées. Par mesure de sécurité, veuillez patienter ' . self::LOCKOUT_MINUTES . ' minutes avant de réessayer.',
                'user' => null,
            ];
        }

        // 2. Look up user by email
        $user = $this->userRepo->findByEmail($email);

        // 3. Verify user existence, status, and password
        // Use generic error message to avoid email enumeration (F-03)
        $invalidMessage = 'Adresse e-mail ou mot de passe incorrect.';

        if ($user === null || !$user->isActive()) {
            // Anti-enumeration: execute dummy password verification to equalize response timing
            $dummyHash = '$argon2id$v=19$m=65536,t=4,p=1$R2pieVgvZUx3Q05xbmRPUw$huoKMl2owZGYnHYDNUcWphizZ1VF7r39nJkhPHtvMqI';
            password_verify($password, $dummyHash);

            $this->recordLoginAttempt($ip, $email);
            return [
                'success' => false,
                'error' => $invalidMessage,
                'user' => null,
            ];
        }

        if (!$user->verifyPassword($password)) {
            $this->recordLoginAttempt($ip, $email);
            return [
                'success' => false,
                'error' => $invalidMessage,
                'user' => null,
            ];
        }

        // Login success: clear login attempts for this IP and email
        $this->clearLoginAttempts($ip, $email);

        // Establish secure session
        $this->startUserSession($user);

        return [
            'success' => true,
            'error' => null,
            'user' => $user,
        ];
    }

    /**
     * Terminate user session completely (F-04).
     */
    public function logout(): void
    {
        if (session_status() === PHP_SESSION_NONE) {
            @session_start();
        }

        // Unset all session variables
        $_SESSION = [];

        // Expire session cookie
        if (ini_get('session.use_cookies') && !headers_sent()) {
            $params = session_get_cookie_params();
            setcookie(
                session_name(),
                '',
                time() - 42000,
                $params['path'],
                $params['domain'],
                $params['secure'],
                $params['httponly']
            );
        }

        // Destroy session server-side
        if (session_status() === PHP_SESSION_ACTIVE) {
            @session_destroy();
        }
    }

    /**
     * Start secure session for authenticated user.
     */
    public function startUserSession(User $user): void
    {
        if (session_status() === PHP_SESSION_NONE && !headers_sent()) {
            @session_start();
        }

        // Prevent session fixation by regenerating session ID
        if (session_status() === PHP_SESSION_ACTIVE && !headers_sent()) {
            @session_regenerate_id(true);
        }

        $_SESSION['user_id'] = $user->id;
        $_SESSION['user_email'] = $user->loginEmail;
        $_SESSION['user_name'] = $user->getFullName();
        $_SESSION['user_password_stamp'] = hash('sha256', (string) $user->passwordHash);
        $_SESSION['last_activity'] = time();
    }

    /**
     * Get currently authenticated user, checking inactivity timeout.
     */
    public function getCurrentUser(): ?User
    {
        if (session_status() === PHP_SESSION_NONE) {
            @session_start();
        }

        $userId = $_SESSION['user_id'] ?? null;
        if (!is_int($userId) && !is_numeric($userId)) {
            return null;
        }

        // Check inactivity expiration
        $lastActivity = $_SESSION['last_activity'] ?? null;
        $lifetime = (int) Env::get('SESSION_LIFETIME', 7200);

        if (is_int($lastActivity) && (time() - $lastActivity > $lifetime)) {
            // Session expired due to inactivity
            $this->logout();
            return null;
        }

        // Refresh last activity timestamp
        $_SESSION['last_activity'] = time();

        $user = $this->userRepo->findById((int) $userId);
        if ($user === null || !$user->isActive()) {
            $this->logout();
            return null;
        }

        // Check password security stamp: invalidates all existing sessions if password was changed
        $savedStamp = $_SESSION['user_password_stamp'] ?? null;
        $currentStamp = hash('sha256', (string) $user->passwordHash);
        if ($savedStamp !== null && !hash_equals($savedStamp, $currentStamp)) {
            $this->logout();
            return null;
        }

        return $user;
    }

    /**
     * Check if client IP or email is currently rate-limited.
     */
    public function isRateLimited(string $ip, string $email): bool
    {
        $since = gmdate('Y-m-d H:i:s', time() - (self::LOCKOUT_MINUTES * 60));
        $emailHash = hash('sha256', strtolower(trim($email)));

        $stmt = $this->pdo->prepare('
            SELECT COUNT(*) FROM `login_attempts`
            WHERE (`ip` = :ip OR `email_hash` = :email_hash)
              AND `attempted_at` >= :since
        ');

        $stmt->execute([
            ':ip' => $ip,
            ':email_hash' => $emailHash,
            ':since' => $since,
        ]);

        $count = (int) $stmt->fetchColumn();
        return $count >= self::MAX_LOGIN_ATTEMPTS;
    }

    /**
     * Record a failed login attempt in UTC.
     */
    public function recordLoginAttempt(string $ip, string $email): void
    {
        $emailHash = hash('sha256', strtolower(trim($email)));
        $now = gmdate('Y-m-d H:i:s');

        $stmt = $this->pdo->prepare('
            INSERT INTO `login_attempts` (`ip`, `email_hash`, `attempted_at`)
            VALUES (:ip, :email_hash, :attempted_at)
        ');

        $stmt->execute([
            ':ip' => $ip,
            ':email_hash' => $emailHash,
            ':attempted_at' => $now,
        ]);
    }

    /**
     * Clear login attempts upon successful login.
     */
    public function clearLoginAttempts(string $ip, string $email): void
    {
        $emailHash = hash('sha256', strtolower(trim($email)));

        $stmt = $this->pdo->prepare('
            DELETE FROM `login_attempts`
            WHERE `ip` = :ip OR `email_hash` = :email_hash
        ');

        $stmt->execute([
            ':ip' => $ip,
            ':email_hash' => $emailHash,
        ]);
    }
}
